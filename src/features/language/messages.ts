// Longest phrases win; a single pass avoids translating Spanish output again.
const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const phrases = new RegExp(Object.keys(spanish).sort((a,b)=>b.length-a.length).map(escape).join("|"), "g");
export function translateText(text: string, language: Language) {
  if (language === "en" || /^\/[A-Za-z0-9_/]+$/.test(text) || /^https?:/.test(text)) return text;
  const exact = spanish[text.trim()];
  if (exact) return text.replace(text.trim(), exact);
  return text.split(/(https?:\/\/\S+|\/[A-Za-z_][A-Za-z0-9_/]*)/).map((part,index)=>index%2?part:part.replace(phrases, match => spanish[match])).join("");
}
